function createIcon(color, emoji) {
    return L.divIcon({
        className: '',
        html: `
            <div style="position: relative; width: 32px; height: 44px; filter: drop-shadow(0 6px 6px rgba(0,0,0,0.35));">
                <div style="
                    position: absolute; top: 0; left: 0;
                    width: 32px; height: 32px;
                    background: radial-gradient(circle at 30% 25%, ${color}dd 0%, ${color} 45%, ${color} 100%);
                    border-radius: 50%;
                    display: flex; align-items: center; justify-content: center;
                    font-size: 15px; color: white;
                    box-shadow: inset 0 -3px 6px rgba(0,0,0,0.15);
                ">
                    <div style="
                        position: absolute; top: 4px; left: 6px;
                        width: 12px; height: 8px;
                        background: rgba(255,255,255,0.55);
                        border-radius: 50%; filter: blur(1.5px);
                    "></div>
                    ${emoji}
                </div>
                <div style="
                    position: absolute; top: 26px; left: 50%;
                    transform: translateX(-50%);
                    width: 0; height: 0;
                    border-left: 9px solid transparent;
                    border-right: 9px solid transparent;
                    border-top: 16px solid ${color};
                "></div>
            </div>
        `,
        iconSize: [32, 44],
        iconAnchor: [16, 44],
        popupAnchor: [0, -44]
    });
}

